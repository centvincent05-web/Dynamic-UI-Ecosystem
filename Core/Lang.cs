    public static bool English => string.Equals(Settings.Current.Language, "en", StringComparison.OrdinalIgnoreCase);

    public static CultureInfo Culture => English ? new CultureInfo("en-US") : new CultureInfo("id-ID");

    /// <summary>Terjemahkan teks Indonesia → English (kalau English dipilih dan terjemahannya ada).</summary>
    public static string T(string id) => English && En.TryGetValue(id, out var en) ? en : id;

    // ---------- terapkan ke elemen XAML (teks statis) ----------

    static readonly DependencyProperty OrigTextProp = DependencyProperty.RegisterAttached("OrigText", typeof(string), typeof(L));
    static readonly DependencyProperty OrigTipProp = DependencyProperty.RegisterAttached("OrigTip", typeof(string), typeof(L));
    static readonly DependencyProperty OrigContentProp = DependencyProperty.RegisterAttached("OrigContent", typeof(string), typeof(L));

    /// <summary>Terjemahkan semua TextBlock, ToolTip, dan isi tombol berupa teks di dalam <paramref name="root"/>.</summary>
    public static void Apply(DependencyObject root)
    {
        if (root is TextBlock tb) Swap(tb, OrigTextProp, tb.Text, v => tb.Text = v);
        if (root is FrameworkElement fe && fe.ToolTip is string tip) Swap(fe, OrigTipProp, tip, v => fe.ToolTip = v);
        if (root is ContentControl cc && cc.Content is string content) Swap(cc, OrigContentProp, content, v => cc.Content = v);
        foreach (var child in LogicalTreeHelper.GetChildren(root))
            if (child is DependencyObject d) Apply(d);
    }

    static void Swap(DependencyObject o, DependencyProperty prop, string current, Action<string> set)
    {
        var orig = (string?)o.GetValue(prop);
        if (orig == null)
        {
            if (!En.ContainsKey(current)) return; // bukan teks statis yang dikenal
            orig = current;
            o.SetValue(prop, orig);
        }
        set(T(orig));
    }

